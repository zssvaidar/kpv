func symlink(t *testing.T, target, link string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(link), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}
}

func TestAGeneratedDirectoryThatIsALinkIsRefusedWhereverItLeads(t *testing.T) {
	t.Parallel()
	for name, target := range map[string]func(p *project) string{
		"to src, inside the root": func(*project) string { return SourceDir },
		"to a sibling directory":  func(p *project) string { return p.root },
		"outside the root":        func(*project) string { return t.TempDir() },
		"nowhere":                 func(*project) string { return "missing" },
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			p := newProject(t)
			symlink(t, target(p), p.generated())
			before := p.whole(t)

			report, err := Run(context.Background(), p.dir, model("orders"), fake)

			if problemOf(t, report, err).Kind != ProblemGeneratedIsLink {
				t.Fatalf("problem %+v", report.Problem)
			}
			sameSnapshot(t, "the whole tree", before, p.whole(t))
			if _, err := Inspect(context.Background(), p.dir); err == nil {
				t.Fatal("inspect followed the link")
			}
		})
	}
}

func TestNothingIsWrittenThroughALinkedDirectoryUnderGenerated(t *testing.T) {
	t.Parallel()
	outside := t.TempDir()
	for name, target := range map[string]string{"into src": "../../src", "out of the root": outside} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			p := newProject(t)
			runOK(t, p, model("orders"), fake)
			symlink(t, target, p.generated("pkg", "inner"))
			before := p.whole(t)
			beforeOutside := snapshot(t, outside)

			report, err := Run(context.Background(), p.dir, model("orders"), fake, emitting(map[string]string{"pkg/inner/handler.go": "overwritten", "pkg/ok.go": "ok"}))

			if problemOf(t, report, err).Kind != ProblemConflicts {
				t.Fatalf("problem %+v", report.Problem)
			}
			wantStatuses(t, report, map[string]Status{"pipeline.txt": StatusUnchanged, "pkg/inner/handler.go": StatusBlocked, "pkg/ok.go": StatusNotWritten})
			if blocked := entryOf(t, report, "pkg/inner/handler.go"); blocked.Reason != ReasonDirectoryIsLink || blocked.At != "pkg/inner" {
				t.Fatalf("blocked %+v", blocked)
			}
			sameSnapshot(t, "the whole tree", before, p.whole(t))
			sameSnapshot(t, "the directory outside the root", beforeOutside, snapshot(t, outside))
		})
	}
}

func TestGeneratedOrADirectoryUnderItThatIsAFileIsReportedAndNotWrittenOver(t *testing.T) {
	t.Parallel()
	p := newProject(t)
	write(t, p.generated(), "a file called generated")
	before := p.whole(t)
	report, err := Run(context.Background(), p.dir, model("orders"), fake)
	if problemOf(t, report, err).Kind != ProblemGeneratedNotDirectory {
		t.Fatalf("problem %+v", report.Problem)
	}
	sameSnapshot(t, "the whole tree", before, p.whole(t))

	q := newProject(t)
	write(t, q.generated("pkg"), "a file where a directory is needed")
	before = q.whole(t)
	report, err = Run(context.Background(), q.dir, model("orders"), emitting(map[string]string{"pkg/deep/x.go": "x"}))
	if problemOf(t, report, err).Kind != ProblemConflicts {
		t.Fatalf("problem %+v", report.Problem)
	}
	if blocked := entryOf(t, report, "pkg/deep/x.go"); blocked.Status != StatusBlocked || blocked.Reason != ReasonDirectoryNotDirectory || blocked.At != "pkg" {
		t.Fatalf("blocked %+v", blocked)
	}
	sameSnapshot(t, "the whole tree", before, q.whole(t))
}

func TestAManifestListedPathThatIsNoLongerARegularFileIsReportedAndLeftInPlace(t *testing.T) {
	t.Parallel()
	outsideFile := filepath.Join(t.TempDir(), "elsewhere.txt")
	write(t, outsideFile, "outside")
	cases := map[string]func(t *testing.T, p *project, path string){
		"a directory": func(t *testing.T, _ *project, path string) {
			if err := os.Mkdir(path, 0o755); err != nil {
				t.Fatal(err)
			}
		},
		"a link to the generated bytes inside the root": func(t *testing.T, p *project, path string) {
			write(t, p.generated("copy.txt"), fakeContent("orders"))
			symlink(t, "copy.txt", path)
		},
		"a link to src": func(t *testing.T, _ *project, path string) { symlink(t, "../src/handler.go", path) },
		"a link out of the root": func(t *testing.T, _ *project, path string) {
			symlink(t, outsideFile, path)
		},
		"a dangling link": func(t *testing.T, _ *project, path string) { symlink(t, "nothing", path) },
	}
	for name, replace := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			p := newProject(t)
			runOK(t, p, model("orders"), fake)
			path := p.generated("pipeline.txt")
			if err := os.Remove(path); err != nil {
				t.Fatal(err)
			}
			replace(t, p, path)
			before := p.whole(t)

			report, err := Run(context.Background(), p.dir, model("orders"), fake)

			if problemOf(t, report, err).Kind != ProblemConflicts {
				t.Fatalf("problem %+v", report.Problem)
			}
			wantStatuses(t, report, map[string]Status{"pipeline.txt": StatusNotRegularFile})
			sameSnapshot(t, "the whole tree", before, p.whole(t))
			if read(t, outsideFile) != "outside" {
				t.Fatal("the file outside the root changed")
			}
			inspection, err := Inspect(context.Background(), p.dir)
			if err != nil || len(inspection.Files) != 1 || inspection.Files[0].Status != InspectNotRegularFile {
				t.Fatalf("inspect %+v %v", inspection, err)
			}
		})
	}
}

func TestAPipelineDirectoryThatNowResolvesOutsideTheRootIsTheGuardsForbidden(t *testing.T) {
	t.Parallel()
	p := newProject(t)
	runOK(t, p, model("orders"), fake)
	outside := t.TempDir()
	write(t, filepath.Join(outside, GeneratedDir, "pipeline.txt"), "outside")
	if err := os.Rename(p.pipe, p.pipe+".moved"); err != nil {
		t.Fatal(err)
	}
	symlink(t, outside, p.pipe)
	beforeOutside := snapshot(t, outside)

	report, err := Run(context.Background(), p.dir, model("payments"), fake)

	problem := problemOf(t, report, err)
	if problem.Kind != ProblemGuard || problem.GuardKind != projectfs.KindForbidden || !projectfs.IsForbidden(err) {
		t.Fatalf("problem %+v, err %v", problem, err)
	}
	sameSnapshot(t, "the directory outside the root", beforeOutside, snapshot(t, outside))
	if _, err := Inspect(context.Background(), p.dir); !projectfs.IsForbidden(err) {
		t.Fatalf("inspect: %v", err)
	}
}

func TestARevokedRootIsTheGuardsForbidden(t *testing.T) {
	t.Parallel()
	p := newProject(t)
	if _, err := p.guard.Revoke(p.root); err != nil {
		t.Fatal(err)
	}
	before := p.whole(t)
	report, err := Run(context.Background(), p.dir, model("orders"), fake)
	if problem := problemOf(t, report, err); problem.Kind != ProblemGuard || problem.GuardKind != projectfs.KindForbidden {
		t.Fatalf("problem %+v", problem)
	}
	sameSnapshot(t, "the whole tree", before, p.whole(t))
}
